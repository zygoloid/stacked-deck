// Freeze the recipes in tools/level-specs/<chapter>.js into
// solutions/levels/<id>.js and report how each one scores.
//
//   node tools/write-solutions.js [chapter|id ...] [--dry] [--par]
//
// A chapter is its number (1-5) or module name (hearts, diamonds, clubs,
// spades, finale); with no arguments every level is written. Only the named
// chapters' (or levels') solution files are touched.
//   --dry   report only; write nothing
//   --par   also rewrite the PAR table (between `// BEGIN PAR` and
//           `// END PAR`) in src/levels/<chapter>.js for the levels written
import { readFileSync, writeFileSync } from 'node:fs';
import { LEVELS, CHAPTER_FILES } from '../src/levels.js';
import { SPECS } from './level-specs.js';
import { buildLevel } from './level-build.js';
import { runTest } from '../src/engine.js';
import { render } from '../src/render.js';
import { fmtHand } from '../src/cards.js';

const args = process.argv.slice(2);
const dry = args.includes('--dry');
const writePar = args.includes('--par') && !dry;
const names = args.filter((a) => !a.startsWith('--'));
const byName = Object.fromEntries(Object.entries(CHAPTER_FILES).map(([n, f]) => [f, Number(n)]));
const chapters = new Set(), ids = new Set();
for (const a of names) {
  if (/^[1-5]$/.test(a)) chapters.add(Number(a));
  else if (byName[a]) chapters.add(byName[a]);
  else if (LEVELS.some((l) => l.id === a)) ids.add(a);
  else { console.error(`unknown chapter or level: ${a}`); process.exit(1); }
}
const wanted = (level) => !names.length || chapters.has(level.chapter) || ids.has(level.id);

const par = new Map(); // chapter -> [[id, {croupiers, rounds}]]
let failed = 0;
for (const level of LEVELS) {
  if (!wanted(level)) continue;
  const spec = SPECS[level.id];
  if (!spec) { console.log(`${level.id}: no spec`); failed++; continue; }
  const cells = spec.cells ?? buildLevel(level.id, spec.nodes, spec.links).cells;
  const all = [...level.fixed, ...cells];
  const results = level.tests.map((t) => runTest({ cells: all }, t, level.pays));
  const ok = results.every((r) => r.ok);
  if (!ok) failed++;
  const rounds = Math.round(results.reduce((a, r) => a + r.rounds, 0) / results.length);
  const floor = new Set(level.floor.map((h) => h.join(',')));
  const off = cells.filter((c) => !floor.has(c.at.join(',')));
  const map = render({ cells: all });
  console.log(`\n== ${level.card ?? ''} ${level.id} ${ok ? 'PASS' : 'FAIL'} croupiers ${cells.length} rounds ${rounds} floor ${level.floor.length}${off.length ? ` OFF-FLOOR ${off.map((c) => c.at).join(' ')}` : ''}`);
  console.log(map.replace(/^/gm, '   '));
  results.forEach((r, i) => {
    if (!r.ok) console.log(`   test ${i} failed (${r.rounds} rounds)${r.timeout ? ' TIMEOUT' : ''} wrong: ${r.wrong.map(fmtHand).join(' ')} missing: ${r.missing.join(' | ')}`);
  });
  if (!par.has(level.chapter)) par.set(level.chapter, []);
  par.get(level.chapter).push([level.id, { croupiers: cells.length, rounds }]);
  if (dry) continue;
  const body = `// Reference solution for "${level.title}" (${level.id}${level.card ? `, floor ${level.card}` : ''}).
// Generated by tools/write-solutions.js from tools/level-specs/${CHAPTER_FILES[level.chapter]}.js;
// only the player's own cells (shoes and croupiers), not the level's fixed cells.
// ${cells.length} croupiers, ${rounds} rounds.
//
${map.replace(/^/gm, '//   ')}
export default {
  cells: [
${cells.map((c) => `    ${JSON.stringify(c)},`).join('\n')}
  ],
};
`;
  writeFileSync(new URL(`../solutions/levels/${level.id}.js`, import.meta.url), body);
}

const entry = (id, p) => `  '${id}': { croupiers: ${p.croupiers}, rounds: ${p.rounds} },`;
for (const [ch, list] of par) {
  console.log(`\n// ${CHAPTER_FILES[ch]}\nconst PAR = {\n${list.map(([id, p]) => entry(id, p)).join('\n')}\n};`);
  if (!writePar) continue;
  const url = new URL(`../src/levels/${CHAPTER_FILES[ch]}.js`, import.meta.url);
  const src = readFileSync(url, 'utf8');
  const m = src.match(/\/\/ BEGIN PAR\n([\s\S]*?)\/\/ END PAR/);
  if (!m) { console.error(`no BEGIN PAR / END PAR block in src/levels/${CHAPTER_FILES[ch]}.js`); failed++; continue; }
  const old = new Map([...m[1].matchAll(/'([^']+)': \{ croupiers: (\d+), rounds: (\d+) \}/g)]
    .map(([, id, c, r]) => [id, { croupiers: Number(c), rounds: Number(r) }]));
  for (const [id, p] of list) old.set(id, p);
  const order = LEVELS.filter((l) => l.chapter === ch).map((l) => l.id);
  const lines = order.filter((id) => old.has(id)).map((id) => entry(id, old.get(id)));
  const block = `// BEGIN PAR\nconst PAR = {\n${lines.join('\n')}\n};\n// END PAR`;
  writeFileSync(url, src.replace(/\/\/ BEGIN PAR\n[\s\S]*?\/\/ END PAR/, block));
  console.log(`(PAR table written to src/levels/${CHAPTER_FILES[ch]}.js)`);
}
if (failed) { console.log(`\n${failed} level(s) failed or have no recipe`); process.exit(1); }
