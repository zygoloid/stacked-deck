// Freeze the recipes in tools/level-specs.js into solutions/levels/<id>.js
// and report how each one scores.
//   node tools/write-solutions.js [id ...]     (default: every level)
//   node tools/write-solutions.js --dry [id]   (report only)
import { writeFileSync } from 'node:fs';
import { LEVELS } from '../src/levels.js';
import { SPECS } from './level-specs.js';
import { buildLevel } from './level-build.js';
import { runTest } from '../src/engine.js';
import { render } from '../src/render.js';
import { fmtHand } from '../src/cards.js';

const args = process.argv.slice(2);
const dry = args.includes('--dry');
const par = [];
const ids = args.filter((a) => a !== '--dry');

for (const level of LEVELS) {
  if (ids.length && !ids.includes(level.id)) continue;
  const spec = SPECS[level.id];
  if (!spec) { console.log(`${level.id}: no spec`); continue; }
  const cells = spec.cells ?? buildLevel(level.id, spec.nodes, spec.links).cells;
  const all = [...level.fixed, ...cells];
  const results = level.tests.map((t) => runTest({ cells: all }, t, level.pays));
  const ok = results.every((r) => r.ok);
  const rounds = Math.round(results.reduce((a, r) => a + r.rounds, 0) / results.length);
  const floor = new Set(level.floor.map((h) => h.join(',')));
  const off = cells.filter((c) => !floor.has(c.at.join(',')));
  const map = render({ cells: all });
  console.log(`\n== ${level.id} ${ok ? 'PASS' : 'FAIL'} croupiers ${cells.length} rounds ${rounds} floor ${level.floor.length}${off.length ? ` OFF-FLOOR ${off.map((c) => c.at).join(' ')}` : ''}`);
  console.log(map.replace(/^/gm, '   '));
  results.forEach((r, i) => {
    if (!r.ok) console.log(`   test ${i} failed (${r.rounds} rounds)${r.timeout ? ' TIMEOUT' : ''} wrong: ${r.wrong.map(fmtHand).join(' ')} missing: ${r.missing.join(' | ')}`);
  });
  par.push(`  '${level.id}': { croupiers: ${cells.length}, rounds: ${rounds} },`);
  if (dry) continue;
  const body = `// Reference solution for "${level.title}" (${level.id}).
// Generated by tools/write-solutions.js from tools/level-specs.js; only the
// player's own cells (shoes and croupiers), not the level's fixed cells.
// ${cells.length} croupiers, ${rounds} rounds.
//
${map.replace(/^/gm, '//   ')}
export default {
  cells: [
${cells.map((c) => `    ${JSON.stringify(c)},`).join('\n')}
  ],
};
`;
  writeFileSync(new URL(`../solutions/levels/${level.id}.js`, import.meta.url), body);
}

console.log('\nconst PAR = {\n' + par.join('\n') + '\n};');
